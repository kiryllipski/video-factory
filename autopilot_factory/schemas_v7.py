    "self_test",     # тест, который зритель делает прямо сейчас + интерпретация
    "number_shock",  # одно число как сюжет: ожидание → развенчание → реальная цифра
    "versus",        # прямое сравнение двух вариантов по критериям + вердикт
    "timeline",      # что происходит за N дней/часов, по этапам
