class Frame(BaseModel):
    """Кадр покрывает ДИАПАЗОН битов, а не один бит (v7). Но диапазон короткий: с 2026-08-13
    один кадр держится на экране **не дольше 3 секунд** (`validate_plan`), кадров на ролик
    9–15. Первая партия v7 шла по 6–7 кадров при 4.3 с на кадр и провалами до 8.4 с без
    смены картинки — замер в `docs/experiments/2026-08-13_v7_review.md`."""
    prompt: str = Field(..., description="Промпт Nano Banana 2 (EN), чистота описана позитивно")
    claim: str = Field(..., min_length=8, max_length=140, description=(
        "Что этот кадр УТВЕРЖДАЕТ, если выключить звук. Если честный ответ «ничего» или "
        "«уют» — кадр надо переписать. Проверяется QA."))
    shot: Shot
    subject: Subject
    beat_from: int = Field(..., ge=0)
    beat_to: int = Field(..., ge=0, description="включительно")
    motion: Motion = "ken_burns_in"
    ref_ids: List[str] = Field(default_factory=list, max_length=3, description=(
        "ID предыдущих кадров как style-refs. Лимит 3 — официальный лимит модели; "
        "старый пайплайн слал 14 и получал style drift (старый бэклог п.10)."))
    aspect: Literal["9:16"] = "9:16"


class FramePlan(BaseModel):
    grade: str
    light: str
    lens: str
    # Нижняя граница намеренно осталась мягкой (5): требование «9-15 кадров» держит гейт
    # `engine_v7.validate_plan`, а не схема. Схема ещё и ЧИТАЕТ старые прогоны с диска
    # (`--rebuild`) — подними здесь порог, и ролики первой партии v7 перестанут пересобираться.
    frames: List[Frame] = Field(..., min_length=5, max_length=16)


