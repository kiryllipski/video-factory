"""
schemas_v7.py — контракты пайплайна v7 (дизайн: docs/experiments/2026-08-12_v7_design.md).

Чем отличается от `schemas.py` (v1-v6) — три структурных изменения, всё остальное следствия:

1. **Формат ролика — поле контракта, а не рубрика в голове.** `Script.format` выбирается из
   каталога (`FORMATS`), и от него зависит драматургия, тип графики и тип заголовка. До v7 все
   100 роликов шли одной структурой «симптом → ошибка → механизм → фикс» — см. аудит §1.1.

2. **Кадры отвязаны от битов.** Раньше был жёсткий контракт frames[i] ↔ beats[i]: кадр
   буквально иллюстрировал фразу. Теперь кадр покрывает ДИАПАЗОН битов
   (`beat_from`..`beat_to`), а внутри диапазона работает графика.
   ⚠️ Правка 2026-08-13: диапазон ограничен сверху — кадр не дольше 3 с, кадров 9–15.
   Первая редакция («кадров 6–10») дала 4.3 с на кадр против исторических 2.49 с у v1–v6 —
   картинка стала реже, а не плотнее. Потолок стоимости поднят до $3, экономить кадры
   больше не нужно.

3. **Слой графики (`Overlay`).** Информация выводится НА ЭКРАН: числа, шкалы, сравнения,
   списки, штампы. До v7 в сборке существовало ровно три текстовых объекта (постер, субтитр,
   CTA-плашка) и ни одной цифры — при том что ниша целиком про дозы, формы и проценты.

Плюс два поля, которые делают качество проверяемым машиной, а не пожеланием в промпте:
`Script.payload` (что зритель уносит) и `Frame.claim` (что кадр утверждает без звука).
"""
