# --- Стадия 1: сценарий ---------------------------------------------------------
Act = Literal["hook", "body", "payoff"]


class Beat(BaseModel):
    """Один смысловой бит. В отличие от v1-v6 длина НЕ равномерная: акт `hook` требует
    коротких битов (0.7-1.6с), акт `body` — средних, акт `payoff` заканчивается коротким.
    Ровный ритм 2.4-3.6с у 84% битов — диагноз старого пайплайна (аудит §1.3)."""
    voiceover: str = Field(..., description="Текст озвучки бита на языке канала")
    on_screen_text: str = Field("", description="Караоке-субтитр, 2-4 слова (фолбэк)")
    visual_cue: str = Field(..., description="Что происходит в кадре — вход для visual_director")
    dur_s: float = Field(..., ge=0.6, le=3.5)
    act: Act = "body"
    emphasis: str = Field("", description=(
        "Одно ключевое слово этого бита (ровно как в voiceover) — сборка подсветит его "
        "и повесит на него звуковой акцент. Пусто = без акцента."))


class Overlay(BaseModel):
    """Графика поверх кадра — главное нововведение v7. Всё рендерится детерминированно
    (CSS/GSAP), стоит $0 и не зависит от того, что нарисовала image-модель."""
    kind: Literal["stat", "bar", "versus", "list", "callout", "stamp", "timeline", "source"]
    beat_idx: int = Field(..., ge=0, description="К какому биту привязана (появляется с ним)")
    # универсальные поля; какие использовать — зависит от kind
    label: str = Field("", max_length=42, description="Подпись/заголовок графики")
    value: str = Field("", max_length=18, description="Число или короткое значение (stat/bar/versus A)")
    label_b: str = Field("", max_length=42, description="versus: подпись правой колонки")
    value_b: str = Field("", max_length=18, description="versus: значение правой колонки")
    percent: Optional[int] = Field(None, ge=0, le=100, description="bar: заполнение шкалы, %")
    items: List[str] = Field(default_factory=list, max_length=4, description=(
        "list: 3-4 однородных пункта одного типа (гейт `engine_v7.validate_script`; нижняя "
        "граница держится гейтом, а не схемой — старые прогоны на диске не должны падать). "
        "timeline: 2-4 строки. Для list префикс '+' = галочка, '-' = крестик, иначе точка."))
    # "none" вместо пустой строки: Gemini structured output отклоняет пустой enum-вариант
    # (400 INVALID_ARGUMENT: enum[0] cannot be empty) — поймано на первом живом прогоне.
    winner: Literal["none", "a", "b"] = Field("none", description=(
        "versus: какая сторона выигрывает; 'none' — вердикта нет"))
    # kind="source" — не микроскопическая сноска, а editorial-карточка. Эти поля заполняются
    # только из переданного Gemini Search research memo; модель не вправе придумывать
    # библиографию. Полный набор полей делает карточку одновременно читаемой и проверяемой.
    source_finding: str = Field("", max_length=120, description=(
        "source: 3-10 слов, вывод исследования на языке канала; не повторяет субтитр"))
    source_title: str = Field("", max_length=180, description="source: точное название работы/базы")
    source_publisher: str = Field("", max_length=80, description="source: журнал, организация или база")
    source_year: str = Field("", max_length=8, description="source: год публикации")
    source_reference: str = Field("", max_length=160, description=(
        "source: URL или домен первоисточника для мелкой строки «Źródło»"))


class Script(BaseModel):
    lang: str = "pl"
    rubric: Rubric = "label"
    format: Format
    hook: str = Field(..., max_length=200, description="Первая фраза; НЕ обязана быть вопросом")
    poster_text: str = Field(..., max_length=48, description=(
        "Крупный текст на кадре-0 с t=0, ≤4 слов, акцент через *звёздочки*"))
    beats: List[Beat] = Field(..., min_length=6, max_length=20)
    overlays: List[Overlay] = Field(default_factory=list, description=(
        "Графика ролика. Минимум на 35% битов — иначе QA не пропустит."))
    payload: str = Field(..., min_length=12, max_length=180, description=(
        "ЧТО КОНКРЕТНО зритель уносит: цифра, доза, интервал, название формы или действие. "
        "Проверяется машиной на наличие конкретики — обобщения вроде «организм решает» "
        "или «badania są niejednoznaczne» не проходят."))
    turn_beat_idx: int = Field(..., ge=0, description=(
        "Индекс бита-поворота: место, где ролик меняет направление («и вот тут неожиданность»). "
        "Должен лежать в акте body. На него сборка ставит звуковой удар."))
    payoff_card: str = Field(..., max_length=80, description=(
        "Текст финальной карточки — то, ради чего ролик сохраняют. Крупным на бренд-фоне. "
        "Это НЕ вопрос и НЕ призыв, а сам вывод."))
    cta: str = Field("", max_length=160, description="Устный CTA последнего бита")
    total_dur_s: float = Field(..., ge=18, le=45)


