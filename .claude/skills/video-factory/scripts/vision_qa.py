def _record(resp, step: str) -> None:
    if _cost is not None:
        try:
            _cost.record_tokens(_MODEL, getattr(resp, "usage_metadata", None), step=step)
        except Exception:
            pass


def check_image(path: str | Path, *, poster: bool = False, still: bool = False,
                expect_texts: list[str] | None = None, profile: str = "photo") -> ImageCheck:
    """Один vision-чек. poster=True добавляет требования к кадру-0; still=True — правила
    готового стоп-кадра; expect_texts — строки, которые ДОЛЖНЫ читаться на кадре (постер/CTA).

    profile — свод правил для frame-QA: `photo` (продакшен, фотореалистичные кадры) или
    `collage` (эксперимент v5: рваная бумага/растр/плоский фон — стиль, а не брак). На
    still-проверку не влияет: готовый кадр оценивается по читаемости текста одинаково."""
    img = Path(path).read_bytes()
    if still:
        rules = _STILL_RULES
    elif profile == "sheet":
        rules = _SHEET_RULES
    elif profile == "collage":
        rules = _COLLAGE_FRAME_RULES + (_COLLAGE_POSTER_EXTRA if poster else "")
    elif profile == "photo_v7":
        rules = _FRAME_RULES_V7 + (_POSTER_EXTRA_V7 if poster else "")
    else:
        rules = _FRAME_RULES + (_POSTER_EXTRA if poster else "")
    ask = rules
    if expect_texts:
        joined = "; ".join(f"«{t}»" for t in expect_texts if t)
        if joined:
            ask += f"\nДополнительно: на кадре ОЖИДАЕТСЯ читаемый текст: {joined} — если его нет/нечитаем, это FAIL."
    ask += "\nВерни строгий JSON по схеме."
    resp = client().models.generate_content(
        model=_MODEL,
        contents=[types.Part.from_bytes(data=img, mime_type="image/png"), ask],
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
            response_schema=ImageCheck,
            temperature=0.1,
        ),
    )
    _record(resp, "vision_qa")
    try:
        return ImageCheck(**json.loads(resp.text))
    except Exception as e:  # не роняем сборку из-за QA — фиксируем как программный сбой чека
        return ImageCheck(passed=True, issues=[f"vision_qa parse error (принято без проверки): {e}"])


def main() -> int:
    ap = argparse.ArgumentParser(description="vision QA кадра/стоп-кадра")
    ap.add_argument("mode", choices=["frame", "still"])
    ap.add_argument("image")
    ap.add_argument("--poster", action="store_true")
    ap.add_argument("--profile", default="photo", choices=["photo", "collage", "sheet"],
                    help="свод правил frame-QA (collage — эксперимент v5)")
    ap.add_argument("--expect-poster", default="")
    ap.add_argument("--expect-cta", default="")
    a = ap.parse_args()
    expect = [t for t in (a.expect_poster, a.expect_cta) if t]
    r = check_image(a.image, poster=a.poster, still=(a.mode == "still"),
                    expect_texts=expect or None, profile=a.profile)
    print(r.model_dump_json(indent=2))
    return 0 if r.passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
